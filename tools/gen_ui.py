"""Turns source/ui.html into source/ui_html.h, so the page is part of the plugin.
Usage: python3 tools/gen_ui.py"""
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, 'source', 'ui.html')
out = os.path.join(root, 'source', 'ui_html.h')
data = open(src, 'rb').read()
if b'\x00' in data:
    sys.exit('ui.html must not contain NUL bytes')
lines = []
for i in range(0, len(data), 16):
    lines.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
with open(out, 'w', newline='\n') as f:
    f.write('// Generated by tools/gen_ui.py from source/ui.html. Do not edit.\n')
    f.write('#ifndef UI_HTML_H\n#define UI_HTML_H\n#include <stddef.h>\n')
    f.write('static const unsigned char ui_html[] = {\n' + '\n'.join(lines) + '\n};\n')
    f.write('static const size_t ui_html_len = %d;\n#endif\n' % len(data))
print('wrote %s (%d bytes of page)' % (out, len(data)))
